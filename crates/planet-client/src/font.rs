//! The font: a 5 by 7 bitmap for the characters a frame's runs can carry.
//!
//! Dependency-light on purpose. A GPU text stack (glyphon) is already in the client for the window
//! loop, but rasterising through it needs a device, and this unit is headless: a bitmap table is
//! inspectable, deterministic, and can be asserted on pixel by pixel. It covers upper case, digits and
//! the punctuation frames use; lower case is folded to upper case and that fold is stated here rather
//! than hidden. Anything else is not drawn — the picture refuses it (`cellframe-glyph`).

/// One cell's width in device-independent pixels: **the format's number**, re-exported, not restated.
pub const CELL_W: u32 = planet_package::cellframe::CELL_W_DP;
/// One cell's height, from the same place.
pub const CELL_H: u32 = planet_package::cellframe::CELL_H_DP;

/// The glyph's rows, top to bottom, five bits each with the leftmost pixel in bit 4.
